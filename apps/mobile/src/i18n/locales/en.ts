/**
 * English — the source catalog.
 *
 * This is the ONLY file where a string is added by hand. `Strings` is inferred
 * from it, every other locale is declared as `Strings`, and so adding a key
 * here breaks the build in six places until they are all filled in. That is
 * the intended workflow: a string that ships untranslated is a string somebody
 * decided to ship untranslated.
 *
 * KEY NAMING is `area.thing`, and the area is where a player SEES it rather
 * than which file renders it — `lobby.waiting`, not `lobbySeat.waiting`. Files
 * get refactored; the screen a player is looking at does not.
 *
 * WRITING RULES, so translators have something to match:
 *   - Sentence case, no trailing period on labels and buttons; full stops only
 *     on sentences.
 *   - `{placeholders}` are named, never positional, because word order changes
 *     between these languages and a translator moving `{name}` must be able to
 *     tell what it holds.
 *   - Anything counting something has an explicit `_one` / `_other` pair.
 */

