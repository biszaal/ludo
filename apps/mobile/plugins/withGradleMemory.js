/**
 * Keep the Android release build inside the EAS free builder's memory.
 *
 * The first SDK 58 production build (1.3.0, 2026-11-16) died in the Gradle step
 * with "Gradle build daemon disappeared unexpectedly" — the OS killing it, not a
 * compile error. EAS forks Gradle with `-Xmx4g -XX:MaxMetaspaceSize=1g` and
 * parallel on, and the Kotlin compiler by default runs as a SECOND daemon that
 * inherits a heap that size. Two ~5 GB JVMs plus Hermes and R8 do not fit; SDK
 * 56 (1.2.3) happened to squeeze under, SDK 58 does not.
 *
 * So Kotlin compiles inside the Gradle process that already has the heap, the
 * Kotlin daemon (if anything still asks for one) is capped, and worker
 * parallelism is held at 2. GRADLE_OPTS from EAS still owns org.gradle.jvmargs;
 * none of these keys conflict with it.
 *
 * A plugin rather than a committed gradle.properties because android/ is
 * generated by prebuild and gitignored.
 */

const { withGradleProperties } = require("expo/config-plugins");

const PROPS = {
  "kotlin.compiler.execution.strategy": "in-process",
  "kotlin.daemon.jvmargs": "-Xmx1536m -XX:MaxMetaspaceSize=512m",
  "org.gradle.workers.max": "2",
};

const withGradleMemory = (config) =>
  withGradleProperties(config, (cfg) => {
    for (const [key, value] of Object.entries(PROPS)) {
      cfg.modResults = cfg.modResults.filter((p) => !(p.type === "property" && p.key === key));
      cfg.modResults.push({ type: "property", key, value });
    }
    return cfg;
  });

module.exports = withGradleMemory;
